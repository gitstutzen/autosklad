"""Общие условия для тестов сервиса.

Две задачи:
  1. Сделать libs/common импортируемым (репозиторий — монорепо, но каждый сервис
     тестируется независимо, поэтому libs не установлен как обычный пакет).
  2. Задать переменные окружения, которые модули читают при импорте.
     Без них падает сам сбор тестов, ещё до первого проверяемого утверждения.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))

# --------------------------------------------------------------------------
# ЖЁСТКО ПЕРЕЗАПИСЫВАЕМ — не setdefault!
#
# Здесь всё, что может увести тесты в боевые системы. Присваивание безусловное
# специально: в окне терминала запросто остаются переменные от запуска пробников
# (они задаются вручную перед probe_*.py и живут до закрытия окна). При setdefault
# побеждали бы они, и тесты молча настроились бы на боевой Stutzen с настоящим
# ключом. Именно это и произошло 02.09.2026 — поймал тест test_env_setup.
#
# На сами пробники это не влияет: они запускаются как отдельные скрипты,
# conftest.py к ним не применяется.
# --------------------------------------------------------------------------

# Заведомо нерабочие адреса: если тест по недосмотру уйдёт в сеть,
# он упадёт на подключении, а не выполнит настоящий запрос к Stutzen.
os.environ["API1C_BASE_URL"] = "https://example.invalid/api1c"
os.environ["API1C_API_KEY"] = "test-key-not-real"
os.environ["TRADESOFT_API_BASE_URL"] = "https://example.invalid/api/v1"
os.environ["TRADESOFT_API_TOKEN"] = "test-token-not-real"
os.environ["CRPT_API_KEY"] = "test-key-not-real"

# SQLite в памяти. Тоже жёстко: если в окружении окажется адрес боевого
# Postgres, тесты начали бы писать в него — а они создают и удаляют таблицы.
os.environ["DATABASE_URL"] = "sqlite://"

# Нерабочий порт: тесты не должны ходить в настоящую очередь задач.
os.environ["REDIS_URL"] = "redis://localhost:6399/0"

# Режим только чтения — на случай, если тест дойдёт до записывающего вызова.
os.environ["STUTZEN_READ_ONLY"] = "true"

# --------------------------------------------------------------------------
# Остальное безопасно оставить как умолчание: эти значения никуда не ведут
# и ничего не могут испортить.
# --------------------------------------------------------------------------

os.environ.setdefault("JWT_SECRET", "test-secret-not-real")
