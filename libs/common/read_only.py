"""
Режим "только чтение" для обращений к внешним системам.

Контекст: у проекта нет тестовой базы и нет отдельного тестового ключа API —
разработка ведётся против боевого контура Stutzen. Поэтому запись наружу
запрещена по умолчанию и включается только явно.

Как это работает:
  STUTZEN_READ_ONLY не задана или "true"  -> запись запрещена (по умолчанию!)
  STUTZEN_READ_ONLY="false"                -> запись разрешена

Умолчание выбрано "запрещено" сознательно: если переменная потерялась при
деплое, опечатана или окружение поднялось не тем конфигом — система откажет
в записи, а не начнёт менять статусы реальных заказов. Ошибка в безопасную
сторону.

Снимать защиту следует только на том контуре, где веб-версия действительно
должна управлять заказами, и осознанно — это не "галочка чтобы заработало".
"""
import os


class WriteBlockedByReadOnlyMode(Exception):
    """Выбрасывается вместо выполнения записывающего вызова к внешней системе."""


def is_read_only() -> bool:
    return os.environ.get("STUTZEN_READ_ONLY", "true").strip().lower() != "false"


def ensure_writes_allowed(operation: str) -> None:
    """Вызывается перед КАЖДОЙ записывающей операцией наружу.

    operation — человекочитаемое описание того, что пытались сделать,
    попадёт в текст ошибки и в лог, чтобы было понятно, что именно заблокировано.
    """
    if is_read_only():
        raise WriteBlockedByReadOnlyMode(
            f"Операция '{operation}' заблокирована: включён режим только чтения "
            f"(STUTZEN_READ_ONLY). Это защита от изменения боевых данных Stutzen "
            f"во время разработки и отладки. Чтобы разрешить запись на этом контуре, "
            f"установите STUTZEN_READ_ONLY=false — только если понимаете последствия."
        )
